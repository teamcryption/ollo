// Generates packages/react/src/generated: one module per asset (tree-shakeable) + index.
import fs from 'node:fs';
import path from 'node:path';
import { REACT_GEN } from './paths.mjs';
import { splitSvg } from './svg.mjs';

const pascal = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const HEADER = '// AUTO-GENERATED by @library/build - do not edit.\n';

export function generateReact({ icons, illustrations, tokens }) {
  fs.rmSync(REACT_GEN, { recursive: true, force: true });
  fs.mkdirSync(path.join(REACT_GEN, 'icons'), { recursive: true });
  fs.mkdirSync(path.join(REACT_GEN, 'illustrations'), { recursive: true });
  const index = [HEADER];

  for (const icon of icons) {
    const comp = `${pascal(icon.name)}Icon`;
    const bodies = {};
    for (const [style, svg] of Object.entries(icon.out)) bodies[style] = splitSvg(svg).body;
    fs.writeFileSync(
      path.join(REACT_GEN, 'icons', `${comp}.tsx`),
      `${HEADER}import { createIcon } from '../../createIcon';\n\n` +
        `/** ${icon.title} - ${icon.category}. Tags: ${icon.tags.join(', ')} */\n` +
        `export const ${comp} = createIcon(${JSON.stringify(icon.name)}, ${JSON.stringify(bodies, null, 2)});\n`
    );
    index.push(`export { ${comp} } from './icons/${comp}';`);
  }

  for (const ill of illustrations) {
    const comp = `${pascal(ill.name)}Illustration`;
    const bodies = {};
    for (const [type, tpl] of Object.entries(ill.templates)) bodies[type] = splitSvg(tpl).body;
    fs.writeFileSync(
      path.join(REACT_GEN, 'illustrations', `${comp}.tsx`),
      `${HEADER}import { createIllustration } from '../../createIllustration';\n\n` +
        `/** ${ill.title} - ${ill.category}. Tags: ${ill.tags.join(', ')} */\n` +
        `export const ${comp} = createIllustration(${JSON.stringify(ill.name)}, ${JSON.stringify(bodies, null, 2)});\n`
    );
    index.push(`export { ${comp} } from './illustrations/${comp}';`);
  }

  fs.writeFileSync(
    path.join(REACT_GEN, 'tokens.ts'),
    `${HEADER}export const tokens = ${JSON.stringify(tokens, null, 2)} as const;\n`
  );
  index.push(`export { tokens } from './tokens';`);
  fs.writeFileSync(path.join(REACT_GEN, 'index.ts'), index.join('\n') + '\n');
  return icons.length + illustrations.length;
}
